from pydantic import BaseModel, Field, model_validator
from typing import List, Dict, Optional


class BeliefVector(BaseModel):
    """
    3D belief probability distribution over verdict states:
    [P(SUPPORTED), P(REFUTED), P(NOT_ENOUGH_INFORMATION)]
    Must satisfy 0 <= p <= 1 and sum(p) == 1.0 (within numerical tolerance).
    """
    supported: float = Field(..., ge=0.0, le=1.0)
    refuted: float = Field(..., ge=0.0, le=1.0)
    unknown: float = Field(..., ge=0.0, le=1.0)

    @model_validator(mode="after")
    def validate_and_normalize(self) -> "BeliefVector":
        total = self.supported + self.refuted + self.unknown
        if total <= 0:
            # Fallback to uniform distribution
            self.supported = 1.0 / 3.0
            self.refuted = 1.0 / 3.0
            self.unknown = 1.0 / 3.0
        elif abs(total - 1.0) > 1e-4:
            # Auto-normalize to sum to 1.0
            self.supported = round(self.supported / total, 4)
            self.refuted = round(self.refuted / total, 4)
            self.unknown = round(1.0 - (self.supported + self.refuted), 4)
        return self

    def to_list(self) -> List[float]:
        return [self.supported, self.refuted, self.unknown]

    @classmethod
    def from_list(cls, values: List[float]) -> "BeliefVector":
        if len(values) != 3:
            raise ValueError("BeliefVector requires exactly 3 values: [supported, refuted, unknown]")
        return cls(supported=values[0], refuted=values[1], unknown=values[2])


class AgentPosition(BaseModel):
    """
    Structured debate argument and position from a reasoning agent.
    """
    agent_name: str = Field(..., description="advocate, skeptic, neutral, or critic")
    claim_id: str
    round_number: int = 0
    position: str = Field(..., description="SUPPORTED, REFUTED, or NOT_ENOUGH_INFORMATION")
    probabilities: BeliefVector
    cited_evidence_ids: List[str] = Field(default_factory=list, description="IDs of cited evidence (e.g. ['E1', 'E3'])")
    reasoning: str = Field(..., description="Detailed argumentative text")
    acknowledged_weaknesses: List[str] = Field(default_factory=list, description="Weaknesses disclosed by the agent")
    confidence: float = Field(..., ge=0.0, le=1.0)


class SocraticChallenge(BaseModel):
    """
    Challenge or probe generated by the Socratic Critic.
    """
    challenge_id: str
    claim_id: str
    target_agent: Optional[str] = None
    question: str
    challenge_type: str = Field("epistemic", description="entity_mismatch, temporal_drift, correlation_causation, unsupported_assumption, contradiction")
    requires_research: bool = False
    suggested_query: Optional[str] = None


class JudgeEvaluation(BaseModel):
    """
    Trust weight allocation and debate assessment produced by the Judge Agent.
    """
    claim_id: str
    round_number: int = 0
    agent_trust_weights: Dict[str, float] = Field(
        ...,
        description="Normalized trust weight for each agent: advocate, skeptic, neutral, critic"
    )
    argument_quality_scores: Dict[str, float] = Field(default_factory=dict)
    evidence_reliance_scores: Dict[str, float] = Field(default_factory=dict)
    rationale: str = Field(..., description="Explanation of why trust weights were assigned")

    @model_validator(mode="after")
    def validate_weights(self) -> "JudgeEvaluation":
        total = sum(self.agent_trust_weights.values())
        if total > 0 and abs(total - 1.0) > 1e-3:
            normalized = {k: round(v / total, 4) for k, v in self.agent_trust_weights.items()}
            # Adjust rounding difference on largest item
            diff = 1.0 - sum(normalized.values())
            max_k = max(normalized, key=normalized.get)
            normalized[max_k] = round(normalized[max_k] + diff, 4)
            self.agent_trust_weights = normalized
        return self
