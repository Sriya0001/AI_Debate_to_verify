from pydantic import BaseModel, Field
from typing import Optional, List
from datetime import datetime


class ResearchTask(BaseModel):
    """
    Research task dynamically generated by the Autonomous Planner.
    """
    task_id: str = Field(..., description="Unique task identifier, e.g., 'T1', 'T2'")
    claim_id: str = Field(..., description="Target claim ID")
    query: str = Field(..., description="Specific search query to execute")
    target_source_type: str = Field("news", description="official, regulatory, academic, news, factcheck")
    purpose: str = Field(..., description="Epistemic purpose of this research task")
    priority: int = Field(1, ge=1, le=3, description="1=high priority, 2=medium, 3=supplementary")


class EvidenceItem(BaseModel):
    """
    Centralized Evidence Item with unique ID, domain, stance, and relevance.
    """
    evidence_id: str = Field(..., description="Unique evidence ID, e.g., 'E1', 'E2'")
    claim_id: str = Field(..., description="Associated claim ID")
    task_id: Optional[str] = Field(None, description="Task ID that retrieved this evidence")
    title: str = Field(..., description="Page or document title")
    url: str = Field(..., description="Source URL")
    snippet: str = Field(..., description="Extracted relevant passage or text")
    source_domain: str = Field(..., description="Extracted domain, e.g., 'reuters.com'")
    retrieved_at: str = Field(default_factory=lambda: datetime.utcnow().isoformat())
    supports_claim: Optional[bool] = Field(None, description="True=supports, False=contradicts, None=neutral/unclear")
    relevance_score: float = Field(0.8, ge=0.0, le=1.0, description="Relevance to the target claim")


class SourceScore(BaseModel):
    """
    Objective credibility evaluation for a source domain or URL.
    """
    source_domain: str
    url: Optional[str] = None
    authority_level: int = Field(..., ge=1, le=6, description="1=Government/Regulator down to 6=Unknown/Low")
    authority_name: str = Field(..., description="e.g., 'Official Government / Regulatory', 'Peer-Reviewed Research'")
    credibility_score: float = Field(..., ge=0.0, le=1.0, description="Normalized credibility score")
    is_independent: bool = Field(True, description="Whether the source is financially/politically independent")
    is_primary: bool = Field(False, description="Whether source is a primary source")
    recency_factor: float = Field(1.0, ge=0.0, le=1.0, description="Recency weighting")
    rationale: str = Field(..., description="Justification for the credibility score")
